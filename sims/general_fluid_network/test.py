import numpy as np
import matplotlib.pyplot as plt
from CoolProp.CoolProp import PropsSI

# ============================================================
# SIM CONTROLS
# ============================================================

dt = 0.1
t_final = 1000.0
N = int(t_final / dt)

# ============================================================
# GAS / TANK
# ============================================================

GAS = "Nitrogen"
V_tank = 0.040        # m^3
A_tank = 0.71         # m^2

# ============================================================
# FILL CONDITIONS
# ============================================================

P_supply = 6000 * 6894.76
P_target = 2500 * 6894.76

T_supply = 305.0
mdot = 0.08          # kg/s

# ============================================================
# THERMAL MODEL (GAS → WALL → AMBIENT)
# ============================================================

h_gw = 150.0          # W/m^2-K  gas → wall
h_wa = 200.0           # W/m^2-K  wall → ambient

C_wall = 1200.0      # J/K
T_amb = 305.0

# ============================================================
# STORAGE
# ============================================================

t = np.zeros(N)
m = np.zeros(N)
U = np.zeros(N)

T_g = np.zeros(N)     # gas temperature
T_w = np.zeros(N)     # wall temperature
P = np.zeros(N)

# ============================================================
# INITIAL CONDITIONS
# ============================================================

P0 = 1e5
T_g[0] = 305.0
T_w[0] = T_amb

rho0 = PropsSI("D", "P", P0, "T", T_g[0], GAS)
m[0] = rho0 * V_tank

u0 = PropsSI("U", "T", T_g[0], "P", P0, GAS)
U[0] = m[0] * u0
P[0] = P0

# Supply enthalpy
h_in = PropsSI("H", "T", T_supply, "P", P_supply, GAS)

# ============================================================
# TIME MARCH
# ============================================================

# OPTIONAL: Increase wall mass to physical levels (approx 40kg steel)
C_wall = 20000.0  # J/K (Adjusted from 1200 for better realism)

for i in range(N - 1):

    t[i+1] = t[i] + dt

    # Stop fill
    if P[i] >= P_target:
        mdot = 0.0

    # Mass update
    m[i+1] = m[i] + mdot * dt

    # -------------------------
    # Heat transfer
    # -------------------------

    Qdot_gw = h_gw * A_tank * (T_g[i] - T_w[i])
    Qdot_wa = h_wa * A_tank * (T_w[i] - T_amb)

    # -------------------------
    # Energy updates
    # -------------------------

    # FIX: Removed manual Qdot_exp subtraction. 
    # The 'h_in' from CoolProp already captures the low enthalpy of the high-pressure supply.
    
    # Gas internal energy (dU/dt = mdot*h_in - Q_loss)
    U[i+1] = U[i] + (mdot * h_in - Qdot_gw) * dt

    # Wall temperature
    T_w[i+1] = T_w[i] + (Qdot_gw - Qdot_wa) * dt / C_wall

    # -------------------------
    # State update (GAS EOS)
    # -------------------------

    rho = m[i+1] / V_tank
    u = U[i+1] / m[i+1]

    # PropsSI handles the T recovery automatically based on u and rho
    T_g[i+1] = PropsSI("T", "U", u, "D", rho, GAS)
    P[i+1] = PropsSI("P", "T", T_g[i+1], "D", rho, GAS)
